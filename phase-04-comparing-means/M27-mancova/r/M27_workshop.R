d <- read.csv("data/practice.csv")
y <- as.matrix(d[c("y","z")])
s <- subset(d,b==0)
pred <- predict(lm(cbind(y,z)~factor(a)+baseline,s),data.frame(a=0:1,baseline=25))
cat("Predicted at baseline 25:\n"); print(pred)
cat("L1:\n")
fit <- manova(cbind(y,z)~baseline+factor(a),s)
for(method in c("Pillai","Wilks","Hotelling-Lawley","Roy")) print(summary(fit,test=method)$stats["factor(a)",])
cat("L2:\n")
fit <- manova(cbind(y,z)~factor(a)*factor(b)+baseline,d)
for(method in c("Pillai","Wilks","Hotelling-Lawley","Roy")) print(summary(fit,test=method)$stats["factor(a):factor(b)",])
cat("L3:\n")
fit <- manova(cbind(y,z)~factor(a)*factor(b)+factor(a)*baseline,d)
for(method in c("Pillai","Wilks","Hotelling-Lawley","Roy")) print(summary(fit,test=method)$stats["factor(a):baseline",])
