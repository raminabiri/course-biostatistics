d <- read.csv("data/practice.csv")
d$a <- factor(d$a)
d$b <- factor(d$b)
d$x <- d$baseline - 25
b0 <- subset(d, b == 0)
one <- manova(cbind(y,z) ~ x + a, data=b0)
cat("L1 adjusted predictions at 25:\n")
print(predict(one, data.frame(x=0, a=factor(c(0,1), levels=levels(d$a)))))
all <- manova(cbind(y,z) ~ x + a*b, data=d)
slopes <- manova(cbind(y,z) ~ x + a*b + a:x, data=d)
cat("L1 effect A in B0:\n"); print(summary(one, test="Pillai")$stats["a", ])
cat("L2 effect A:B:\n"); print(summary(all, test="Pillai")$stats["a:b", ])
cat("L3 effect A:x:\n"); print(summary(slopes, test="Pillai")$stats["x:a", ])
print(coef(all))
print(coef(slopes))
