d <- read.csv("data/practice.csv")
d$a <- factor(d$a)
d$b <- factor(d$b)
g <- mean(d$value)
a <- ave(d$value,d$a)
b <- ave(d$value,d$b)
cell <- ave(d$value,d$a,d$b)
aligned <- list(a=d$value-cell+a-g,b=d$value-cell+b-g,interaction=d$value-a-b+g)
terms <- c("a","b","a:b")
for(i in seq_along(terms)) {
  fit <- anova(lm(rank(round(aligned[[i]],10))~a*b,d))
  cat("L1",terms[i],fit[terms[i],"F value"],fit[terms[i],"Pr(>F)"],"\n")
}
r <- rank(d$value)
fit <- anova(lm(r~a*b,d))
h <- fit[terms,"Sum Sq"]/(sum((r-mean(r))^2)/(length(r)-1))
cat("L2:",h,pchisq(h,1,lower.tail=FALSE),"\n")
